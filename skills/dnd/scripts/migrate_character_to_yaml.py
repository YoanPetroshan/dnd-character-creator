#!/usr/bin/env python3
"""
migrate_character_to_yaml.py — one-time converter from the old freeform
characters/<slug>.md to the new char_state YAML schema.

Usage:
    python3 migrate_character_to_yaml.py <campaign> <slug>

Backs up the original markdown to <slug>.md.pre-migration before writing
the new YAML (the .md itself gets regenerated by char_state afterward).

Scope — what this does and does not convert
-------------------------------------------
The parser is regex-based and deliberately narrow. It converts identity,
ability scores, combat stats, currency and backstory. It leaves these at
their schema defaults:

    proficiencies, features_traits, personality, spellcasting,
    ability_scores beyond the standard six-column table, player, speed
    beyond the "**Speed:** N ft" line, and hp_max beyond "**HP:** c / m"

Those are CREATION-TIME fields: set once when a character is created or
migrated, then essentially never mutated during play. Finishing them off
with a single direct edit of the new <slug>.yaml — reading the values out
of the .md.pre-migration backup — is the correct, sanctioned way to
complete a migration. It is not a workaround, and it does not conflict
with this system's "never freeform-edit" rule.

That rule is specifically about two things:
  * the GENERATED characters/<slug>.md, which must never be hand-edited
    because char_state.py overwrites it from the YAML on the next write; and
  * ongoing-play state — HP, conditions, inventory, currency, spell-slot
    usage, levels — which must go through char_state.py so the arithmetic
    is validated instead of drifting turn after turn.

The source <slug>.yaml is a different thing. Authoring it directly at
creation or migration time is the intended entry point; there is no CLI
setter for these fields precisely because they aren't play-time state.
"""
from __future__ import annotations

import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)
import paths  # noqa: E402
from char_state_schema import (  # noqa: E402
    AbilityScores, Character, ClassLevel, CombatStats, Conditions, Currency,
    Personality, Proficiencies, save_character,
)

_IDENTITY_RE = re.compile(
    r"\*\*Race:\*\*\s*([^|]+)\|\s*\*\*Class:\*\*\s*([^(|]+)(?:\(([^)]+)\))?\s*\|\s*\*\*Level:\*\*\s*(\d+)"
    r"\s*\|\s*\*\*Background:\*\*\s*([^\n]+)"
)
_ALIGNMENT_RE = re.compile(r"\*\*Alignment:\*\*\s*([^|]+)")
_HP_RE = re.compile(r"\*\*HP:\*\*\s*(\d+)\s*/\s*(\d+)")
_SPEED_RE = re.compile(r"\*\*Speed:\*\*\s*(\d+)\s*ft")
_SCORES_ROW_RE = re.compile(r"\|\s*(\d+)\s*\([+-]?\d+\)\s*\|\s*(\d+)\s*\([+-]?\d+\)\s*\|\s*(\d+)\s*\([+-]?\d+\)\s*"
                             r"\|\s*(\d+)\s*\([+-]?\d+\)\s*\|\s*(\d+)\s*\([+-]?\d+\)\s*\|\s*(\d+)\s*\([+-]?\d+\)\s*\|")
_CURRENCY_RE = re.compile(r"\*\*Currency:\*\*\s*(\d+)gp\s*(\d+)sp\s*(\d+)cp")
_NAME_RE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
_BACKSTORY_RE = re.compile(r"## Backstory & Notes\s*\n(.+)", re.DOTALL)


def parse_markdown_character(text: str) -> Character:
    name_m = _NAME_RE.search(text)
    if not name_m:
        raise ValueError("could not find a top-level '# Name' heading in the character file")
    name = name_m.group(1).strip()

    identity = _IDENTITY_RE.search(text)
    if not identity:
        raise ValueError(
            "could not find the '**Race:** ... **Class:** ... **Level:** ... **Background:** ...' identity line"
        )
    race = identity.group(1).strip()
    cls = identity.group(2).strip()
    subclass = (identity.group(3) or "").strip()
    level = int(identity.group(4))
    background = identity.group(5).strip()

    alignment_m = _ALIGNMENT_RE.search(text)
    alignment = alignment_m.group(1).strip() if alignment_m else ""

    scores_m = _SCORES_ROW_RE.search(text)
    scores = AbilityScores(*(int(g) for g in scores_m.groups())) if scores_m else AbilityScores(10, 10, 10, 10, 10, 10)

    hp_m = _HP_RE.search(text)
    hp_current, hp_max = (int(hp_m.group(1)), int(hp_m.group(2))) if hp_m else (0, 0)
    speed_m = _SPEED_RE.search(text)
    speed = int(speed_m.group(1)) if speed_m else 30

    currency_m = _CURRENCY_RE.search(text)
    currency = Currency(gp=int(currency_m.group(1)), sp=int(currency_m.group(2)), cp=int(currency_m.group(3))) if currency_m else Currency()

    backstory_m = _BACKSTORY_RE.search(text)
    backstory = backstory_m.group(1).strip() if backstory_m else ""

    return Character(
        name=name, race=race, background=background, alignment=alignment, player="",
        classes=[ClassLevel(cls=cls, subclass=subclass, level=level)],
        ability_scores=scores,
        combat=CombatStats(hp_current=hp_current, hp_max=hp_max, speed=speed),
        proficiencies=Proficiencies(),
        conditions=Conditions(), personality=Personality(), features_traits=[], backstory=backstory,
        currency=currency, equipment=[], misc_items=[], spellcasting=[], spells=[],
        spell_slots={}, pact_magic_slots=None,
    )


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: migrate_character_to_yaml.py <campaign> <slug>", file=sys.stderr)
        return 1
    campaign, slug = sys.argv[1], sys.argv[2]
    md_path = paths.find_campaign(campaign) / "characters" / f"{slug}.md"
    if not md_path.exists():
        print(f"error: no such file {md_path}", file=sys.stderr)
        return 1
    text = md_path.read_text(encoding="utf-8")
    char = parse_markdown_character(text)
    backup = md_path.with_suffix(".md.pre-migration")
    backup.write_text(text, encoding="utf-8")
    save_character(campaign, slug, char)
    print(f"OK: wrote {slug}.yaml, backed up original to {backup.name}")
    print()
    print("NEXT STEP — finish the migration by hand (this is expected, not a failure):")
    print()
    print("  The regex parser converts identity, ability scores, combat, currency and")
    print("  backstory only. These are left at their schema defaults and need filling in:")
    print()
    print("      proficiencies, features_traits, personality, spellcasting,")
    print("      player, and any equipment / spells from the old freeform tables")
    print()
    print(f"  Open characters/{slug}.yaml, compare it against {backup.name},")
    print("  and fill those sections in directly. These are CREATION-TIME fields — set")
    print("  once, then essentially never mutated during play — so editing the YAML")
    print("  source once here is the correct, sanctioned way to complete a migration,")
    print("  not a workaround. There is no CLI setter for them by design.")
    print()
    print("  This does NOT contradict the \"never hand-edit\" rule. That rule covers the")
    print(f"  GENERATED characters/{slug}.md (char_state.py overwrites it from the YAML")
    print("  on every write, so edits there are silently lost) and ongoing-play state —")
    print("  HP, conditions, inventory, currency, spell slots, levels — which must go")
    print("  through char_state.py so the arithmetic stays validated. The YAML source at")
    print("  creation/migration time is a different thing, and editing it here is fine.")
    print()
    print(f"  Then verify with: python3 char_state.py {campaign} {slug} --get all")
    return 0


if __name__ == "__main__":
    sys.exit(main())
